export function modbusCrc16(data: Uint8Array): number {
  let crcHi = 0xff;
  let crcLo = 0xff;
  for (const byte of data) {
    const idx = (crcHi ^ byte) & 0xff;
    crcHi = crcLo ^ CRC_HI[idx];
    crcLo = CRC_LO[idx];
  }
  return ((crcLo << 8) | crcHi) & 0xffff;
}

/** Read command frame (old protocol, no infoData) -- see PROTOCOL.md's "Request Frame (Read)". */
export function buildReadFrame(address: number, frameHead: number = FRAME_HEAD, readCount = 0): Uint8Array {
  const buf = new Uint8Array(11);
  buf[0] = frameHead;
  buf[1] = 0x00; // version (old protocol)
  buf[2] = DEVICE_ADDR;
  buf[3] = FUNC_READ;
  buf[4] = (address >> 8) & 0xff;
  buf[5] = address & 0xff;
  buf[6] = (readCount >> 8) & 0xff;
  buf[7] = readCount & 0xff;
  const crc = modbusCrc16(buf.subarray(0, 8));
  buf[8] = (crc >> 8) & 0xff;
  buf[9] = crc & 0xff;
  buf[10] = FRAME_TAIL;
  return buf;
}

/** From the first notification packet's DATA_LEN field: total expected response length. */
export function expectedResponseLength(firstPacket: Uint8Array): number | null {
  if (firstPacket.length < 8) return null;
  const dataLen = (firstPacket[6] << 8) | firstPacket[7];
  return dataLen + 11;
}

export interface WattFrame {
  version: number;
  address: number;
  functionCode: number;
  startAddress: number;
  dataLength: number;
  data: Uint8Array;
}

export function parseFrame(data: Uint8Array): WattFrame | null {
  if (data.length < MIN_FRAME_SIZE) return null;
  if (data[0] !== FRAME_HEAD && data[0] !== FRAME_HEAD_ALT) return null;
  if (data[data.length - 1] !== FRAME_TAIL) return null;

  const functionCode = data[3];
  if (functionCode === FUNC_ERROR) return null;
  // CRC mismatch is warning-only upstream (wattcycle_ble logs but doesn't
  // reject) -- not treated as fatal here either.

  const startAddress = (data[4] << 8) | data[5];
  const dataLength = (data[6] << 8) | data[7];
  return {
    version: data[1],
    address: data[2],
    functionCode,
    startAddress,
    dataLength,
    data: data.slice(8, 8 + dataLength),
  };
}

export interface AnalogQuantity {
  current: number;
  moduleVoltage: number;
  soc: number;
}

/** Bit 7 of byte 0: sign. Bit 6: decimal flag. Bits 5-0 + byte 1: magnitude. */
function parseCurrentNegative(data: Uint8Array, offset: number): [current: number, nextOffset: number] {
  const b0 = data[offset];
  const b1 = data[offset + 1];
  const isNegative = (b0 & 0x80) !== 0;
  const hasDecimal = (b0 & 0x40) !== 0;
  const raw = b1 | ((b0 & 0x3f) << 8);
  let current = hasDecimal ? raw / 10.0 : raw;
  if (isNegative) current = -current;
  return [current, offset + 2];
}

/**
 * Analog Quantity response payload (DP 140). Only current/moduleVoltage are
 * actually needed (to compute watts), but every field before them must
 * still be walked over to land on the right byte offsets -- see
 * PROTOCOL.md's "Response Parsing: Analog Quantity" for the full layout.
 */
export function parseAnalogQuantity(data: Uint8Array): AnalogQuantity | null {
  try {
    let off = 0;

    const cellCount = data[off];
    off += 1;
    off += cellCount * 2; // cellVoltages, unused here

    const temperatureCount = data[off];
    off += 1;
    off += 2; // mosTemperature, unused
    off += 2; // pcbTemperature, unused
    off += Math.max(temperatureCount - 2, 0) * 2; // cellTemperatures, unused

    const [current, offAfterCurrent] = parseCurrentNegative(data, off);
    off = offAfterCurrent;

    const moduleVoltage = ((data[off] << 8) | data[off + 1]) / 100.0;
    off += 2;

    off += 2; // remainingCapacity, unused
    off += 2; // totalCapacity, unused
    off += 2; // cycleNumber, unused
    off += 2; // designCapacity, unused

    const soc = (data[off] << 8) | data[off + 1];

    return { current, moduleVoltage, soc };
  } catch {
    return null;
  }
}
